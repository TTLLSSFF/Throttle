/// Look up an executable file name (lower case, with extension).
pub fn lookup(exe_file_name: &str) -> Option<(&'static str, &'static str)> {
    ENTRIES
        .iter()
        .find(|(exe, _, _)| *exe == exe_file_name)
        .map(|(_, english, chinese)| (*english, *chinese))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_applications_have_both_names() {
        let (english, chinese) = lookup("chrome.exe").expect("chrome is known");
        assert_eq!(english, "Google Chrome");
        assert_eq!(chinese, "谷歌浏览器");
        assert!(lookup("discord.exe").is_some());
        let (english, chinese) = lookup("msmpeng.exe").expect("Defender is known");
        assert_eq!(english, "Microsoft Defender Antivirus");
        assert_eq!(chinese, "微软 Defender 杀毒");
        assert!(lookup("clash-verge.exe").is_some());
        assert!(lookup("vmmem").is_some());
    }

    #[test]
    fn unknown_executables_are_not_guessed() {
        assert!(lookup("definitely-not-an-app.exe").is_none());
        assert!(lookup("chrome").is_none());
    }

    #[test]
    fn keys_are_unique_lower_case_file_names() {
        let mut seen = std::collections::HashSet::new();
        for (exe, english, chinese) in ENTRIES {
            assert_eq!(*exe, exe.to_lowercase(), "{exe} is not lower case");
            assert!(!exe.contains('\\') && !exe.contains('/'), "{exe} is a path");
            assert!(!english.is_empty() && !chinese.is_empty(), "{exe} is blank");
            assert!(seen.insert(*exe), "{exe} appears twice");
        }
        assert!(ENTRIES.len() >= 250, "the dictionary should stay useful");
    }
}
